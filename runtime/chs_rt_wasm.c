#include "chs_rt.h"

/* OPEN-28 path A: valid empty MVP module. Not compiled source bytecode. */
void oo_wasm_write_empty_module(void) {
  static const unsigned char m[] = {
      0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, /* \0asm v1 */
      0x01, 0x04, 0x01, 0x60, 0x00, 0x00,             /* type []->[] */
      0x03, 0x02, 0x01, 0x00,                         /* 1 func type0 */
      0x07, 0x0a, 0x01, 0x06, 0x5f, 0x73, 0x74, 0x61, 0x72, 0x74, 0x00,
      0x00, /* export _start */
      0x0a, 0x04, 0x01, 0x02, 0x00, 0x0b              /* code end */
  };
  fwrite(m, 1, sizeof m, stdout);
  fflush(stdout);
}
